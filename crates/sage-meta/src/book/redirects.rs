//! Preserve published chapter and rule URLs without adding canonical definitions.
use std::collections::BTreeMap;
use std::error::Error;
use std::path::{Component, Path};

use serde_json::Value;

const GENERATED: &str = "<!-- Generated by sage-meta redirects. -->";

#[derive(Default, serde::Serialize)]
struct Redirects {
    default: Option<String>,
    fragments: BTreeMap<String, String>,
}

// {anchor}`meta.book.anchor_moves`
pub(super) fn apply(context: &Value, sections: &mut [Value]) -> Result<(), Box<dyn Error>> {
    let root = Path::new(
        context
            .get("root")
            .and_then(Value::as_str)
            .ok_or("mdBook context must specify its root")?,
    );
    let source = sage_meta::workspace::book_source_root(root)?;
    let manifest = source.join("anchor-redirects.json");
    if !manifest.is_file() {
        return Ok(());
    }
    let entries: BTreeMap<String, String> =
        serde_json::from_str(&std::fs::read_to_string(manifest)?)?;
    let mut pages = BTreeMap::<String, Redirects>::new();
    for (from, to) in &entries {
        let (page, fragment) = split_url(from);
        validate_path(page)?;
        validate_path(split_url(to).0)?;
        let relative = sage_meta::spec::relative_url(page, to);
        let redirects = pages.entry(page.into()).or_default();
        if let Some(fragment) = fragment {
            if fragment.is_empty() {
                return Err(format!("empty redirect fragment in `{from}`").into());
            }
            redirects.fragments.insert(fragment.into(), relative);
        } else {
            redirects.default = Some(relative);
        }
    }
    // Default moves preserve unrecognized fragments, so cycle checking includes
    // fragments from every alias rather than considering exact map keys alone.
    let mut fragments = std::collections::BTreeSet::from([String::new()]);
    for url in entries.keys().chain(entries.values()) {
        if let Some(fragment) = split_url(url).1 {
            fragments.insert(fragment.into());
        }
    }
    let active = pages
        .keys()
        .filter(|path| chapter_at(sections, path).is_some())
        .cloned()
        .collect::<std::collections::BTreeSet<_>>();
    for page in pages.keys() {
        for fragment in &fragments {
            let mut seen = std::collections::BTreeSet::new();
            let mut next = if fragment.is_empty() {
                page.clone()
            } else {
                format!("{page}#{fragment}")
            };
            loop {
                if !seen.insert(next.clone()) {
                    return Err(format!("redirect cycle involving `{next}`").into());
                }
                let (path, fragment) = split_url(&next);
                let specific = entries.get(&next).filter(|_| fragment.is_some());
                let target = specific.or_else(|| {
                    if active.contains(path) {
                        None
                    } else {
                        entries.get(path)
                    }
                });
                let Some(target) = target else {
                    break;
                };
                next = if specific.is_none() && split_url(target).1.is_none_or(str::is_empty) {
                    match fragment {
                        Some(fragment) => format!("{}#{fragment}", split_url(target).0),
                        None => target.clone(),
                    }
                } else {
                    target.clone()
                };
            }
        }
    }
    let mut writes = Vec::new();
    for (path, mut redirects) in pages {
        if let Some(chapter) = chapter_at(sections, &path) {
            // A current chapter remains readable. Only retired fragments redirect.
            redirects.default = None;
            if !redirects.fragments.is_empty() {
                let current = chapter
                    .get("content")
                    .and_then(Value::as_str)
                    .unwrap_or_default();
                chapter["content"] = format!("{current}\n{}", script(&redirects)?).into();
            }
            continue;
        }
        let output = source.join(&path);
        for ancestor in output.ancestors().take_while(|path| *path != source) {
            if ancestor.is_symlink() {
                return Err(
                    format!("redirect output follows a symlink: {}", ancestor.display()).into(),
                );
            }
        }
        let html = document(&redirects)?;
        if output.exists() {
            let current = std::fs::read_to_string(&output)?;
            if !current.starts_with(GENERATED) {
                return Err(format!(
                    "refusing to overwrite handwritten redirect output {}",
                    output.display()
                )
                .into());
            }
            if current == html {
                continue;
            }
        }
        writes.push((output, html));
    }
    for (path, html) in writes {
        std::fs::create_dir_all(path.parent().ok_or("redirect has no parent")?)?;
        std::fs::write(path, html)?;
    }
    Ok(())
}

fn split_url(url: &str) -> (&str, Option<&str>) {
    url.split_once('#')
        .map_or((url, None), |(page, fragment)| (page, Some(fragment)))
}

fn validate_path(path: &str) -> Result<(), Box<dyn Error>> {
    if path.is_empty()
        || !path.ends_with(".html")
        || path.contains(['\\', ':', '?', '%'])
        || Path::new(path).is_absolute()
        || Path::new(path)
            .components()
            .any(|component| !matches!(component, Component::Normal(_)))
        || path.split('/').any(str::is_empty)
    {
        return Err(format!(
            "redirect path must be a relative .html path without traversal: `{path}`"
        )
        .into());
    }
    Ok(())
}

fn chapter_at<'a>(sections: &'a mut [Value], output: &str) -> Option<&'a mut Value> {
    for item in sections {
        let Some(chapter) = item.get_mut("Chapter") else {
            continue;
        };
        if chapter
            .get("path")
            .and_then(Value::as_str)
            .is_some_and(|path| sage_meta::spec::chapter_url(path) == output)
        {
            return Some(chapter);
        }
        if let Some(children) = chapter.get_mut("sub_items").and_then(Value::as_array_mut)
            && let Some(found) = chapter_at(children, output)
        {
            return Some(found);
        }
    }
    None
}

fn script(redirects: &Redirects) -> Result<String, Box<dyn Error>> {
    let data = serde_json::to_string(redirects)?
        .replace('<', "\\u003c")
        .replace('&', "\\u0026");
    Ok(format!(
        r#"<script>
(()=>{{
const redirects={data};
function redirect(){{
  let fragment=location.hash.slice(1);
  try{{fragment=decodeURIComponent(fragment)}}catch{{}}
  const specific=Object.prototype.hasOwnProperty.call(redirects.fragments,fragment);
  const target=specific?redirects.fragments[fragment]:redirects.default;
  if(!target)return;
  const url=new URL(target,location.href);
  if(!specific&&!url.hash)url.hash=location.hash;
  if(url.href!==location.href)location.replace(url.href);
}}
redirect();
addEventListener('hashchange',redirect);
}})();
</script>"#
    ))
}

fn escape(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&#39;")
}

fn document(redirects: &Redirects) -> Result<String, Box<dyn Error>> {
    let mut links = String::new();
    if let Some(target) = &redirects.default {
        links.push_str(&format!(
            "<p><a href=\"{}\">Open the current chapter</a></p>",
            escape(target)
        ));
    }
    if !redirects.fragments.is_empty() {
        links.push_str("<ul>");
        for (name, target) in &redirects.fragments {
            links.push_str(&format!(
                "<li><a href=\"{}\">{}</a></li>",
                escape(target),
                escape(name)
            ));
        }
        links.push_str("</ul>");
    }
    Ok(format!(
        "{GENERATED}\n<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\"><title>Specification moved</title>{}</head><body><h1>Specification moved</h1>{links}</body></html>\n",
        script(redirects)?
    ))
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;
    struct Fixture(std::path::PathBuf);
    impl Fixture {
        fn new(entries: Value) -> Self {
            static NEXT: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);
            let root = std::env::temp_dir().join(format!(
                "sage-redirects-{}-{}",
                std::process::id(),
                NEXT.fetch_add(1, std::sync::atomic::Ordering::Relaxed)
            ));
            std::fs::create_dir_all(root.join("manual")).unwrap();
            std::fs::write(root.join("book.toml"), "[book]\nsrc = 'manual'\n").unwrap();
            std::fs::write(
                root.join("manual/anchor-redirects.json"),
                serde_json::to_string(&entries).unwrap(),
            )
            .unwrap();
            Self(root)
        }
        fn context(&self) -> Value {
            json!({"root":self.0})
        }
    }
    impl Drop for Fixture {
        fn drop(&mut self) {
            std::fs::remove_dir_all(&self.0).unwrap();
        }
    }

    #[test]
    #[sage::test(meta.book.anchor_moves)]
    fn retired_pages_have_relative_default_and_fragment_redirects() {
        let fixture = Fixture::new(
            json!({"design/old.html":"design/crates/demo/guide.html", "design/old.html#old-rule":"design/anchor/demo/new_rule.html"}),
        );
        let mut chapters = vec![];
        apply(&fixture.context(), &mut chapters).unwrap();
        let html = std::fs::read_to_string(fixture.0.join("manual/design/old.html")).unwrap();
        assert!(html.starts_with(GENERATED));
        assert!(html.contains("\"default\":\"crates/demo/guide.html\""));
        assert!(html.contains("\"old-rule\":\"anchor/demo/new_rule.html\""));
        assert!(html.contains("new URL(target,location.href)"));
        assert!(html.contains("if(!specific&&!url.hash)url.hash=location.hash"));
        assert!(
            chapters.is_empty(),
            "redirects must not add canonical chapters"
        );
        apply(&fixture.context(), &mut chapters).unwrap();
        assert_eq!(
            std::fs::read_to_string(fixture.0.join("manual/design/old.html")).unwrap(),
            html
        );
    }

    #[test]
    #[sage::test(meta.book.anchor_moves)]
    fn active_landing_pages_keep_content_and_only_redirect_retired_fragments() {
        let fixture =
            Fixture::new(json!({"design/meta/index.html#old":"design/anchor/meta/new.html"}));
        let mut chapters = vec![
            json!({"Chapter":{"path":"design/meta/README.md","content":"Current specification","sub_items":[]}}),
        ];
        apply(&fixture.context(), &mut chapters).unwrap();
        let content = chapters[0]["Chapter"]["content"].as_str().unwrap();
        assert!(content.starts_with("Current specification"));
        assert!(content.contains("\"default\":null"));
        assert!(content.contains("\"old\":\"../anchor/meta/new.html\""));
        assert!(!fixture.0.join("manual/design/meta/index.html").exists());
    }

    #[test]
    fn redirects_reject_traversal_cycles_and_handwritten_output() {
        for (source, target) in [
            ("../escape.html", "design/new.html"),
            ("design/old.html", "https://example.com/new.html"),
            ("design/old.html", "design/%2e%2e/new.html"),
            ("design/old.html", "../new.html"),
        ] {
            let fixture = Fixture::new(json!({source:target}));
            assert!(apply(&fixture.context(), &mut []).is_err());
        }
        let fixture = Fixture::new(json!({"old.html":"other.html", "other.html":"old.html"}));
        assert!(
            apply(&fixture.context(), &mut [])
                .unwrap_err()
                .to_string()
                .contains("cycle")
        );
        let inherited = Fixture::new(json!({"a.html":"b.html", "b.html#x":"a.html#x"}));
        assert!(
            apply(&inherited.context(), &mut [])
                .unwrap_err()
                .to_string()
                .contains("cycle")
        );
        let fixture = Fixture::new(json!({"old.html":"new.html"}));
        std::fs::write(fixture.0.join("manual/old.html"), "Handwritten content").unwrap();
        assert!(
            apply(&fixture.context(), &mut [])
                .unwrap_err()
                .to_string()
                .contains("handwritten")
        );
        assert_eq!(
            std::fs::read_to_string(fixture.0.join("manual/old.html")).unwrap(),
            "Handwritten content"
        );
    }

    #[test]
    fn redirect_data_cannot_escape_its_script_or_html_link() {
        let fixture = Fixture::new(
            json!({"old.html#</script><script>alert(1)</script>":"new.html#\"<script>"}),
        );
        apply(&fixture.context(), &mut []).unwrap();
        let html = std::fs::read_to_string(fixture.0.join("manual/old.html")).unwrap();
        assert_eq!(html.matches("</script>").count(), 1);
        assert!(html.contains("\\u003c/script>"));
        assert!(html.contains("new.html#&quot;&lt;script&gt;"));
    }
}
